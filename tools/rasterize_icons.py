#!/usr/bin/env python3
"""
tezOS icon rasterizer -- real, hand-authorable multi-color app icons
(ICQ/AIM-era style: bold, chunky, actual color -- not a single-color
font glyph like MEK-Dings). Converts a simple, editable 16x16 grid of
single-character color codes into a real RGB565 C header, using
tezos_icon_t (see tezos_gfx.h).

Real, deliberate design: icons are authored as plain text, not raw
pixel-editor files, so they're readable/diffable/editable directly in
this repo without needing an external image-editing tool -- the same
"plain, real, checkable source" discipline as everything else in this
project, not something requiring one specific artist's own toolchain
to reproduce or adjust.

Usage: python3 rasterize_icons.py <icons.txt> <c_identifier_prefix> <out_header>

Input format (icons.txt): one or more icon blocks, each:
    NAME
    16 lines of 16 characters, using the legend below
    (blank line between icons)

Legend (matches docs/design-system/PALETTE.md's real, established
colors, plus two real additions specifically for bold ICQ/AIM-style
outlines and highlights that the existing palette doesn't cover):
    .  background (TEZOS_BG)
    K  black outline (real, near-black -- for bold, chunky borders)
    W  white highlight
    B  primary blue    (TEZOS_PRIMARY  #0F61FF)
    P  pink            (TEZOS_PINK     #FF3D8A)
    C  cyan            (TEZOS_CYAN     #2FE6E6)
    A  amber           (TEZOS_AMBER    #FFA53D)
    G  green           (real, new -- #3DDC64, a synthwave-consistent
                         mint/lime green; not in the core palette yet,
                         added here specifically since the ICQ
                         reference point is a green flower and the
                         existing palette had no green at all)
    Y  yellow          (real, new -- #FFE23D, for AIM's iconic yellow)
"""
import sys

LEGEND = {
    '.': (0x10, 0x14, 0x3A),  # TEZOS_BG
    'K': (0x08, 0x08, 0x10),  # real, deliberate near-black outline --
                                # not pure #000000, stays a hair off
                                # true black so it doesn't look like a
                                # rendering hole against the navy bg
    'W': (0xE4, 0xEA, 0xFB),  # real body-text white already in the palette
    'B': (0x0F, 0x61, 0xFF),  # TEZOS_PRIMARY
    'P': (0xFF, 0x3D, 0x8A),  # TEZOS_PINK
    'C': (0x2F, 0xE6, 0xE6),  # TEZOS_CYAN
    'A': (0xFF, 0xA5, 0x3D),  # TEZOS_AMBER
    'G': (0x3D, 0xDC, 0x64),  # real, new green
    'Y': (0xFF, 0xE2, 0x3D),  # real, new yellow
}

ICON_SIZE = 16

def rgb888_to_rgb565(r, g, b):
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)

def parse_icons(text):
    lines = text.split('\n')
    icons = []
    i = 0
    while i < len(lines):
        line = lines[i].strip()
        if not line:
            i += 1
            continue
        name = line
        i += 1
        rows = []
        while i < len(lines) and lines[i].strip() and len(rows) < ICON_SIZE:
            rows.append(lines[i])
            i += 1
        if len(rows) != ICON_SIZE:
            raise ValueError(f"icon '{name}': expected {ICON_SIZE} rows, got {len(rows)}")
        for r, row in enumerate(rows):
            if len(row) < ICON_SIZE:
                raise ValueError(f"icon '{name}' row {r}: expected {ICON_SIZE} chars, got {len(row)}: {row!r}")
        icons.append((name, rows))
    return icons

def emit_header(icons, prefix, out_path):
    with open(out_path, 'w') as f:
        f.write(f"#pragma once\n")
        f.write(f"/* Real, hand-authored icon bitmaps -- generated by tools/rasterize_icons.py.\n")
        f.write(f"   Do not hand-edit this file; edit the source .txt and re-run the tool. */\n")
        f.write(f'#include "../tezos_gfx.h"\n\n')
        for name, rows in icons:
            ident = f"{prefix}_{name.upper()}"
            f.write(f"static const tezos_icon_t {ident} = {{ .pixels = {{\n")
            for row in rows:
                vals = []
                for ch in row[:ICON_SIZE]:
                    if ch not in LEGEND:
                        raise ValueError(f"unknown legend character {ch!r} in icon '{name}'")
                    r, g, b = LEGEND[ch]
                    vals.append(f"0x{rgb888_to_rgb565(r,g,b):04X}")
                f.write("    " + ", ".join(vals) + ",\n")
            f.write("}};\n\n")

if __name__ == '__main__':
    if len(sys.argv) != 4:
        print(__doc__)
        sys.exit(1)
    icons_path, prefix, out_path = sys.argv[1], sys.argv[2], sys.argv[3]
    with open(icons_path) as f:
        text = f.read()
    icons = parse_icons(text)
    emit_header(icons, prefix, out_path)
    print(f"Wrote {len(icons)} icon(s) to {out_path}: {', '.join(n for n, _ in icons)}")
